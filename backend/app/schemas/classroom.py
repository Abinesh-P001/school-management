from datetime import datetime
from pydantic import BaseModel, Field

class ClassroomBase(BaseModel):
    name: str = Field(..., min_length=2, max_length=100) # e.g. "Grade 10"
    section: str = Field(..., min_length=1, max_length=50) # e.g. "A"
    room: str | None = Field(default=None, max_length=100)
    capacity: int = Field(default=35, ge=5, le=100)
    class_teacher_id: int | None = None
    schedule: str | None = Field(default="Mon - Fri, 8:00 AM - 3:00 PM", max_length=200)

class ClassroomCreate(ClassroomBase):
    class_code: str | None = None # Autogenerated if not provided

class ClassroomUpdate(BaseModel):
    name: str | None = None
    section: str | None = None
    room: str | None = None
    capacity: int | None = None
    class_teacher_id: int | None = None
    schedule: str | None = None

class TeacherSummary(BaseModel):
    id: int
    name: str
    email: str
    department: str

    class Config:
        from_attributes = True

class ClassroomResponse(ClassroomBase):
    id: int
    class_code: str
    class_teacher: TeacherSummary | None = None
    student_count: int = 0
    created_at: datetime

    class Config:
        from_attributes = True
