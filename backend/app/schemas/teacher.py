from datetime import datetime
from pydantic import BaseModel, EmailStr, Field

class TeacherBase(BaseModel):
    name: str = Field(..., min_length=2, max_length=150)
    email: EmailStr
    phone: str | None = Field(default=None, max_length=30)
    department: str = Field(..., min_length=2, max_length=100)
    subject: str = Field(..., min_length=2, max_length=150)
    qualification: str | None = Field(default=None, max_length=200)
    experience: str | None = Field(default=None, max_length=50)
    status: str = Field(default="Active", pattern="^(Active|On Leave|Retired)$")

class TeacherCreate(TeacherBase):
    employee_id: str | None = None # Autogenerated if not provided

class TeacherUpdate(BaseModel):
    name: str | None = Field(default=None, min_length=2, max_length=150)
    email: EmailStr | None = None
    phone: str | None = None
    department: str | None = None
    subject: str | None = None
    qualification: str | None = None
    experience: str | None = None
    status: str | None = Field(default=None, pattern="^(Active|On Leave|Retired)$")

class TeacherResponse(TeacherBase):
    id: int
    employee_id: str
    user_id: int | None
    created_at: datetime
    updated_at: datetime

    class Config:
        from_attributes = True
