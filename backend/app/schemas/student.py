from datetime import date, datetime
from pydantic import BaseModel, EmailStr, Field

class StudentBase(BaseModel):
    name: str = Field(..., min_length=2, max_length=150)
    email: EmailStr | None = None
    gender: str = Field(default="Other")
    date_of_birth: date | None = None
    guardian_name: str = Field(..., min_length=2, max_length=150)
    guardian_phone: str = Field(..., min_length=7, max_length=30)
    class_id: int | None = None
    admission_number: str | None = None
    status: str = Field(default="Active", pattern="^(Active|Suspended|Graduated)$")
    fees_status: str = Field(default="Pending", pattern="^(Paid|Pending|Overdue)$")

class StudentCreate(StudentBase):
    student_id: str | None = None # Autogenerated if not provided
    roll_number: str | None = None # Autogenerated if not provided
    admission_date: date | None = None

class StudentUpdate(BaseModel):
    name: str | None = Field(default=None, min_length=2, max_length=150)
    email: EmailStr | None = None
    gender: str | None = None
    date_of_birth: date | None = None
    guardian_name: str | None = None
    guardian_phone: str | None = None
    class_id: int | None = None
    admission_number: str | None = None
    status: str | None = Field(default=None, pattern="^(Active|Suspended|Graduated)$")
    fees_status: str | None = Field(default=None, pattern="^(Paid|Pending|Overdue)$")

class StudentClassInfo(BaseModel):
    id: int
    class_code: str
    name: str
    section: str
    room: str | None

    class Config:
        from_attributes = True

class StudentResponse(BaseModel):
    id: int
    student_id: str
    admission_number: str | None = None
    roll_number: str
    name: str
    email: str
    gender: str
    date_of_birth: date | None
    guardian_name: str
    guardian_phone: str
    admission_date: date
    status: str
    fees_status: str
    class_id: int | None
    classroom: StudentClassInfo | None = None
    invitation_link: str | None = None
    created_at: datetime
    updated_at: datetime
    gender: str
    date_of_birth: date | None
    guardian_name: str
    guardian_phone: str
    admission_date: date
    status: str
    fees_status: str
    class_id: int | None
    classroom: StudentClassInfo | None = None
    created_at: datetime
    updated_at: datetime

    class Config:
        from_attributes = True
