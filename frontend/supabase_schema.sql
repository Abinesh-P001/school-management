-- Helper functions for RBAC
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN public.current_user_role() IN ('admin', 'principal');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.is_teacher()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN public.current_user_role() = 'teacher';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.current_student_ids()
RETURNS TABLE(id BIGINT) AS $$
BEGIN
    RETURN QUERY
    SELECT s.id FROM public.students s
    WHERE s.user_id = auth.uid()
       OR s.email = (current_setting('request.jwt.claims', true)::json->>'email');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop existing policies if re-running
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT policyname, tablename 
        FROM pg_policies 
        WHERE schemaname = 'public'
    ) LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', r.policyname, r.tablename);
    END LOOP;
END $$;

-- Profiles: Own profile or Admin
CREATE POLICY "profiles_select_policy" ON public.profiles FOR SELECT USING (auth.uid() = id OR public.is_admin());
CREATE POLICY "profiles_write_policy" ON public.profiles FOR ALL USING (auth.uid() = id OR public.is_admin()) WITH CHECK (auth.uid() = id OR public.is_admin());

-- Students: Student reads own record; Admin/Faculty reads all; Admin writes
CREATE POLICY "students_select_policy" ON public.students FOR SELECT USING (
    public.is_admin() 
    OR public.is_teacher() 
    OR user_id = auth.uid() 
    OR email = (current_setting('request.jwt.claims', true)::json->>'email')
    OR auth.role() = 'anon'
);
CREATE POLICY "students_insert_admin_only" ON public.students FOR INSERT WITH CHECK (public.is_admin());
CREATE POLICY "students_update_admin_only" ON public.students FOR UPDATE USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "students_delete_admin_only" ON public.students FOR DELETE USING (public.is_admin());

-- Teachers: Directory readable; Admin writes only
CREATE POLICY "teachers_select_policy" ON public.teachers FOR SELECT USING (true);
CREATE POLICY "teachers_write_admin_only" ON public.teachers FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

-- Marks: Student reads own marks ONLY; Faculty & Admin reads/writes; Admin deletes
CREATE POLICY "marks_select_policy" ON public.marks FOR SELECT USING (
    public.is_admin()
    OR public.is_teacher()
    OR student_id IN (SELECT id FROM public.current_student_ids())
    OR auth.role() = 'anon'
);
CREATE POLICY "marks_write_faculty_admin" ON public.marks FOR INSERT WITH CHECK (public.is_admin() OR public.is_teacher());
CREATE POLICY "marks_update_faculty_admin" ON public.marks FOR UPDATE USING (public.is_admin() OR public.is_teacher()) WITH CHECK (public.is_admin() OR public.is_teacher());
CREATE POLICY "marks_delete_admin_only" ON public.marks FOR DELETE USING (public.is_admin());

-- Attendance: Student reads own attendance; Admin & Teacher read & write
CREATE POLICY "attendance_select_policy" ON public.attendance FOR SELECT USING (
    public.is_admin()
    OR public.is_teacher()
    OR student_id IN (SELECT id FROM public.current_student_ids())
    OR auth.role() = 'anon'
);
CREATE POLICY "attendance_write_faculty_admin" ON public.attendance FOR ALL USING (public.is_admin() OR public.is_teacher()) WITH CHECK (public.is_admin() OR public.is_teacher());

-- Fees: Student reads own invoices; Admin reads/writes full ledger; Teachers have NO access
CREATE POLICY "fees_select_policy" ON public.fee_invoices FOR SELECT USING (
    public.is_admin()
    OR student_id IN (SELECT id FROM public.current_student_ids())
    OR auth.role() = 'anon'
);
CREATE POLICY "fees_write_admin_only" ON public.fee_invoices FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

-- Classes, Examinations, Notices, Activities
CREATE POLICY "classes_select_policy" ON public.classes FOR SELECT USING (true);
CREATE POLICY "classes_write_admin_only" ON public.classes FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

CREATE POLICY "examinations_select_policy" ON public.examinations FOR SELECT USING (true);
CREATE POLICY "examinations_write_policy" ON public.examinations FOR ALL USING (public.is_admin() OR public.is_teacher()) WITH CHECK (public.is_admin() OR public.is_teacher());

CREATE POLICY "notices_select_policy" ON public.school_notices FOR SELECT USING (true);
CREATE POLICY "notices_write_admin_only" ON public.school_notices FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

CREATE POLICY "activities_select_policy" ON public.recent_activities FOR SELECT USING (true);
CREATE POLICY "activities_insert_policy" ON public.recent_activities FOR INSERT WITH CHECK (true);


