-- Enable UUID extension if not already enabled
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 1. PROFILES TABLE (Linked with Supabase auth.users)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('admin', 'teacher', 'student', 'Admin', 'Teacher', 'Student')),
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Helper function to extract user role from auth.users or profiles
CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS TEXT AS $$
BEGIN
    RETURN LOWER(COALESCE(
        current_setting('request.jwt.claims', true)::json->'user_metadata'->>'role',
        (SELECT role FROM public.profiles WHERE id = auth.uid()),
        'anon'
    ));
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- ==============================================================================
-- 2. CLASSES TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,                -- e.g. "Grade 10"
    section TEXT NOT NULL,             -- e.g. "A"
    room TEXT,                         -- e.g. "Building B - Room 204"
    capacity INTEGER NOT NULL DEFAULT 35,
    class_teacher TEXT,                -- Teacher name
    schedule TEXT DEFAULT 'Mon - Fri, 8:00 AM - 3:00 PM',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 3. TEACHERS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id TEXT NOT NULL UNIQUE,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    department TEXT NOT NULL,
    subject TEXT NOT NULL,
    qualification TEXT,
    experience TEXT,
    status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'On Leave', 'Retired')),
    salary_status TEXT DEFAULT 'Processed',
    avatar TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 4. STUDENTS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL UNIQUE,    -- e.g. "STU-1001"
    roll_number TEXT NOT NULL UNIQUE,   -- e.g. "10A-01"
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    class_id BIGINT REFERENCES public.classes(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    grade TEXT NOT NULL,                -- e.g. "Grade 10"
    section TEXT NOT NULL DEFAULT 'A',
    gender TEXT NOT NULL CHECK (gender IN ('Male', 'Female', 'Other')),
    date_of_birth DATE,
    guardian_name TEXT NOT NULL,
    guardian_phone TEXT NOT NULL,
    admission_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Suspended', 'Graduated')),
    fees_status TEXT NOT NULL DEFAULT 'Pending' CHECK (fees_status IN ('Paid', 'Pending', 'Overdue')),
    avatar TEXT,
    gpa TEXT DEFAULT '3.80',
    attendance_pct TEXT DEFAULT '95%',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 5. ATTENDANCE TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    student_name TEXT NOT NULL,
    class_name TEXT NOT NULL DEFAULT 'Grade 10-A',
    roll TEXT,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'Present' CHECK (status IN ('Present', 'Absent', 'Late', 'Excused')),
    remarks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uk_student_attendance_date UNIQUE (student_id, date)
);

-- ==============================================================================
-- 6. EXAMINATIONS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.examinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_code TEXT NOT NULL UNIQUE,     -- e.g. "EXM-301"
    name TEXT NOT NULL,                -- e.g. "Mid-Term Examination 2026"
    class_name TEXT NOT NULL,          -- e.g. "Grade 10"
    subject TEXT NOT NULL,
    exam_date DATE NOT NULL,
    time_slot TEXT,
    total_marks INTEGER NOT NULL DEFAULT 100,
    passing_marks INTEGER NOT NULL DEFAULT 40,
    status TEXT NOT NULL DEFAULT 'Upcoming' CHECK (status IN ('Upcoming', 'Ongoing', 'Completed')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 7. MARKS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examination_id BIGINT REFERENCES public.examinations(id) ON DELETE CASCADE,
    exam_name TEXT NOT NULL,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    student_name TEXT NOT NULL,
    subject TEXT NOT NULL,
    score NUMERIC(5, 2) NOT NULL,
    max_score NUMERIC(5, 2) NOT NULL DEFAULT 100,
    grade TEXT NOT NULL,                -- e.g. "A+", "B", "Passed"
    status TEXT NOT NULL CHECK (status IN ('Passed', 'Failed')),
    remarks TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT uk_exam_student_mark UNIQUE (examination_id, student_id)
);

-- ==============================================================================
-- 8. FEE INVOICES & LEDGER TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.fee_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number TEXT NOT NULL UNIQUE, -- e.g. "INV-2026-081"
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    student_name TEXT NOT NULL,
    grade TEXT,
    fee_type TEXT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    due_date DATE NOT NULL,
    paid_date DATE,
    payment_method TEXT,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Paid', 'Pending', 'Overdue')),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 9. SCHOOL NOTICES & ANNOUNCEMENTS TABLE
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.school_notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    summary TEXT NOT NULL,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 10. RECENT ACTIVITIES TABLE
